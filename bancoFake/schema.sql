CREATE DATABASE IF NOT EXISTS beneficiarios
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE beneficiarios;

DROP TABLE IF EXISTS beneficiarios;

CREATE TABLE beneficiarios (
    operadora                   VARCHAR(100),
    convenio                    VARCHAR(100),
    grupo                       VARCHAR(50),
    subsestipulante             VARCHAR(100),
    data_proximo_reajuste       DATE,
    codigo_contrato             VARCHAR(50),
    data_suspensao              DATE,
    data_cancelamento           DATE,
    data_exclusao               DATE,
    motivo_cancelamento         VARCHAR(255),
    numero_proposta             VARCHAR(50),
    data_inclusao               DATE,
    dias_permanencia            SMALLINT,
    plano                       VARCHAR(100),
    acomodacao                  VARCHAR(50),
    documento_corretor          VARCHAR(20),
    nome_corretor                VARCHAR(150),
    documento_supervisor        VARCHAR(20),
    nome_supervisor              VARCHAR(150),
    id_beneficiario              VARCHAR(50) PRIMARY KEY,
    codigo_beneficiario          VARCHAR(50),
    marca_otica                  VARCHAR(100),
    marca_otica_opcional         VARCHAR(100),
    data_marca_otica             DATE,
    marca_otica_assistencial     VARCHAR(100),
    nome_beneficiario            VARCHAR(150),
    data_nascimento              DATE,
    idade                        TINYINT UNSIGNED,
    rg                           VARCHAR(20),
    orgao_emissor                VARCHAR(20),
    cpf                          VARCHAR(14),
    dnv                          VARCHAR(20),
    cns                          VARCHAR(20),
    pis                          VARCHAR(20),
    nome_mae                     VARCHAR(150),
    endereco                     VARCHAR(150),
    numero                       VARCHAR(10),
    complemento                  VARCHAR(50),
    bairro                       VARCHAR(100),
    municipio                    VARCHAR(100),
    uf                           CHAR(2),
    cep                          VARCHAR(9),
    ddd_telefone                 TINYINT UNSIGNED,
    telefone                     VARCHAR(15),
    ddd_celular                  TINYINT UNSIGNED,
    celular                      VARCHAR(15),
    email_principal               VARCHAR(150),
    email_secundario              VARCHAR(150),
    altura                       DECIMAL(3,2),
    peso                         DECIMAL(5,2),
    vigencia                     DATE,
    carencia                     VARCHAR(100),
    estado_civil                 VARCHAR(20),
    tipo_beneficiario            ENUM('Titular','Dependente') NOT NULL,
    sexo                         CHAR(1),
    parentesco                   VARCHAR(30),
    status                       ENUM('Ativo','Suspenso','Cancelado','Excluido') NOT NULL,
    alerta                       VARCHAR(255),
    bloqueio_comissao_etiqueta    VARCHAR(50),
    etiqueta                     VARCHAR(50),
    valor_contrato                DECIMAL(10,2),

    INDEX idx_cpf (cpf),
    INDEX idx_celular (celular),
    INDEX idx_nome (nome_beneficiario),
    INDEX idx_codigo_contrato (codigo_contrato)
) ENGINE=InnoDB;
